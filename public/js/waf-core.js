// WAF Fingerprint — pure, DOM-free core. Inspects response headers (and an
// optional body snippet) for signatures of common WAFs / CDNs / reverse
// proxies, so you know what's in front of the API before choosing tactics.
// DOM-free for `node --test`.

// Each signature: name + predicates over a lower-cased header map and body.
const SIGNATURES = [
  { name: 'Cloudflare', test: (h, b) => h['server']?.includes('cloudflare') || 'cf-ray' in h || 'cf-cache-status' in h || /attention required|cloudflare/i.test(b) },
  { name: 'Akamai', test: (h, b) => h['server']?.includes('akamai') || 'x-akamai-transformed' in h || /akamai/i.test(h['x-cache'] || '') || /akamaighost/i.test(b) },
  { name: 'AWS (CloudFront/ALB/WAF)', test: (h, b) => h['server'] === 'awselb/2.0' || (h['server'] || '').includes('cloudfront') || 'x-amz-cf-id' in h || 'x-amzn-requestid' in h || 'x-amzn-waf-action' in h },
  { name: 'Imperva / Incapsula', test: (h, b) => 'x-iinfo' in h || /incap_ses|visid_incap/i.test(h['set-cookie'] || '') || /incapsula/i.test(b) },
  { name: 'F5 BIG-IP ASM', test: (h, b) => /bigipserver|ts[0-9a-f]{8}/i.test(h['set-cookie'] || '') || /the requested url was rejected/i.test(b) },
  { name: 'Sucuri CloudProxy', test: (h, b) => 'x-sucuri-id' in h || 'x-sucuri-cache' in h || /sucuri/i.test(h['server'] || '') },
  { name: 'Fastly', test: (h) => (h['server'] || '').includes('fastly') || /fastly/i.test(h['x-served-by'] || '') || 'x-fastly-request-id' in h },
  { name: 'Azure Front Door / App Gateway', test: (h) => 'x-azure-ref' in h || 'x-msedge-ref' in h || /microsoft-azure-application-gateway/i.test(h['server'] || '') },
  { name: 'ModSecurity', test: (h, b) => /mod_security|modsecurity/i.test(h['server'] || '') || /this error was generated by mod_security/i.test(b) },
  { name: 'Barracuda', test: (h, b) => /barra_counter_session|barracuda/i.test(h['set-cookie'] || '') || /barracuda/i.test(b) },
  { name: 'Wordfence', test: (h, b) => /wordfence/i.test(b) || /generated by wordfence/i.test(b) },
  { name: 'Nginx', test: (h) => (h['server'] || '').startsWith('nginx') },
  { name: 'Apache', test: (h) => (h['server'] || '').startsWith('apache') },
];

// Parse a raw header block into a lower-cased map (Set-Cookie values joined).
export function parseHeaderMap(raw) {
  const map = {};
  for (const line of String(raw || '').split('\n')) {
    const s = line.trim();
    if (!s || /^HTTP\//i.test(s)) continue;
    const i = s.indexOf(':');
    if (i === -1) continue;
    const name = s.slice(0, i).trim().toLowerCase();
    const value = s.slice(i + 1).trim();
    map[name] = name in map ? map[name] + '; ' + value : value;
  }
  return map;
}

// Identify WAFs/CDNs from a header map + optional body. Returns string[] of names.
export function fingerprint(headerMap, body = '') {
  const h = headerMap || {};
  const b = String(body || '');
  const hits = [];
  for (const sig of SIGNATURES) {
    try {
      if (sig.test(h, b)) hits.push(sig.name);
    } catch {
      /* a missing header just means no match */
    }
  }
  return hits;
}

// Convenience: parse a raw header block + body and fingerprint in one call.
export function fingerprintRaw(rawHeaders, body = '') {
  return fingerprint(parseHeaderMap(rawHeaders), body);
}
